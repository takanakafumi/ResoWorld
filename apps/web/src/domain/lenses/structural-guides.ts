/**
 * トピック情報から対応する4層構造ガイド（Thesis, ReadingGuide, HistoricalContext, FieldInsight）を安全に解決する
 */
export function getTopicStructuralGuide(topic: {
  id: string;
  label?: string;
  description?: string;
}): TopicStructuralGuide {
  const guide = TOPIC_STRUCTURAL_GUIDES[topic.id];
  if (guide) {
    return guide;
  }

  // 宣言的フォールバック
  const thesis = topic.description ?? `${topic.label ?? "トピック"}の構造と関係性の配置`;
  return {
    thesis,
    readingGuide:
      "図中のノードや関係線をクリックすることで、関連する歴史的エンティティや現地スポットの詳細を確認できます。",
    historicalContext:
      topic.description ??
      "古代から近世にかけての歴史的資料および現地遺構に基づく構造関係です。",
    fieldInsight:
      "現地を訪れた際の景観や社殿・遺構配置と照らし合わせることで、空間的な意味の重なりを体感できます。",
  };
}

export function getTopicStructuralThesis(topic: {
  id: string;
  label?: string;
  description?: string;
}): string {
  return getTopicStructuralGuide(topic).thesis;
}
